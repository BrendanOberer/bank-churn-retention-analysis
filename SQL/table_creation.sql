CREATE TABLE bank_data (
    customer_id VARCHAR(20) PRIMARY KEY,
    attrition_status VARCHAR(25) NOT NULL,
    customer_age INT NOT NULL,
    gender CHAR(1) NOT NULL,
    dependent_count INT NOT NULL,
    education_level VARCHAR(25) NOT NULL,
    marital_status VARCHAR(15) NOT NULL,
    income_category VARCHAR(25) NOT NULL,
    card_category VARCHAR(10) NOT NULL,
    customer_tenure_months INT NOT NULL,
    total_relationship_count INT NOT NULL,
    months_inactive_12_mon INT NOT NULL,
    contacts_count_12_mon INT NOT NULL,
    credit_limit DECIMAL(15, 2) NOT NULL,
    total_revolving_bal DECIMAL(15, 2) NOT NULL,
    avg_open_to_buy DECIMAL(15, 2) NOT NULL,
    total_amt_chng_q4_q1 DECIMAL(15, 4) NOT NULL,
    total_trans_amt INT NOT NULL,
    total_trans_ct INT NOT NULL,
    total_ct_chng_q4_q1 DECIMAL(15, 4) NOT NULL,
    avg_utilization_ratio DECIMAL(15, 4) NOT NULL,
    churned SMALLINT NOT NULL,

    CHECK (customer_age BETWEEN 18 AND 100),
    CHECK (months_inactive_12_mon BETWEEN 0 AND 12),
    CHECK (total_relationship_count >= 1),
    CHECK (credit_limit >= 0),
    CHECK (total_trans_amt >= 0),
    CHECK (avg_utilization_ratio BETWEEN 0 AND 1),
    CHECK (churned IN (0, 1))
);